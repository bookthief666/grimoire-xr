import { readFileSync, writeFileSync } from 'node:fs';

const block = lines => lines.join('\n');

const patchFile = (relativePath, edits) => {
  const path = new URL(`../${relativePath}`, import.meta.url);
  let source = readFileSync(path, 'utf8');
  const original = source;

  for (const [label, before, after] of edits) {
    const matches = source.split(before).length - 1;
    if (matches !== 1) {
      throw new Error(`${relativePath} / ${label}: expected exactly one source match, found ${matches}. No files were written.`);
    }
    source = source.replace(before, after);
  }

  return { path, source, original };
};

